def _get_age_key(age_months: int, tips_dict: dict) -> str:
    for key in tips_dict:
        if key == "default":
            continue
        parts = key.split("-")
        if len(parts) == 2:
            lo, hi = int(parts[0]), int(parts[1])
            if lo <= age_months < hi:
                return key
    return "default"


def get_daily_tip(age_months: int, day_of_year: int) -> str:
    key = _get_age_key(age_months, DAILY_TIPS)
    tips = DAILY_TIPS[key]
    return tips[day_of_year % len(tips)]


def get_game_tip(age_months: int, day: int) -> str:
    key = _get_age_key(age_months, GAME_TIPS)
    tips = GAME_TIPS[key]
    return tips[day % len(tips)]


def get_speech_tip(age_months: int, day: int) -> str:
    key = _get_age_key(age_months, SPEECH_TIPS)
    tips = SPEECH_TIPS[key]
    return tips[day % len(tips)]


def get_food_tip(age_months: int, day: int) -> str:
    key = _get_age_key(age_months, FOOD_TIPS)
    tips = FOOD_TIPS[key]
    return tips[day % len(tips)]


def get_evening_reminder(day: int) -> str:
    return EVENING_REMINDERS[day % len(EVENING_REMINDERS)]
